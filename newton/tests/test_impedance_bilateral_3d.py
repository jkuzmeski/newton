def _grid_artifact() -> dict:
    """A 3 x 3 column grid with neighbor slots ordered -x, +x, -y, +y."""
    raw = _tiny_artifact()
    points, neighbors = [], []
    index = {}
    for i, x in enumerate((-0.01, 0.0, 0.01)):
        for j, y in enumerate((-0.01, 0.0, 0.012)):
            index[(i, j)] = len(points)
            points.append([x, y, 0.0])
    for i in range(3):
        for j in range(3):
            neighbors.append(
                [
                    index.get((i - 1, j), -1),
                    index.get((i + 1, j), -1),
                    index.get((i, j - 1), -1),
                    index.get((i, j + 1), -1),
                ]
            )
    raw["column_bed"].update(
        anchor_bottom_m=points,
        neighbors=neighbors,
        rest_length_m=[0.02] * 9,
        area_m2=[1e-4] * 9,
        column_count=9,
    )
    raw["visual_meshes"] = {"last": {"vertices_m": [[0, 0, 0], [1, 0, 0], [0, 1, 0]], "triangles": [[0, 1, 2]]}}
    raw.pop("instron_fixtures", None)
    return raw


class TestMirroredShoe(unittest.TestCase):
    def test_mirror_reflects_geometry_and_neighbor_slots(self):
        """Reflection negates y, swaps the -y/+y neighbor slots, reverses winding, and is an involution."""
        raw = _grid_artifact()
        mirrored = mirror_artifact(copy.deepcopy(raw), source_sha256="abc")
        points = np.asarray(raw["column_bed"]["anchor_bottom_m"])
        mirrored_points = np.asarray(mirrored["column_bed"]["anchor_bottom_m"])
        np.testing.assert_allclose(mirrored_points, points * [1, -1, 1])
        neighbors = np.asarray(mirrored["column_bed"]["neighbors"])
        for column, row in enumerate(neighbors):
            for slot, direction in enumerate(([-1, 0], [1, 0], [0, -1], [0, 1])):
                if row[slot] >= 0:
                    step = mirrored_points[row[slot], :2] - mirrored_points[column, :2]
                    self.assertGreater(np.dot(step, direction), 0.0)
        self.assertEqual(mirrored["visual_meshes"]["last"]["triangles"], [[0, 2, 1]])
        self.assertEqual(mirrored["provenance"]["mirror"]["source_sha256"], "abc")
        again = mirror_artifact(mirrored)
        np.testing.assert_allclose(again["column_bed"]["anchor_bottom_m"], points)
        self.assertEqual(again["column_bed"]["neighbors"], raw["column_bed"]["neighbors"])


def _calibration(seed: int = 0) -> k.Calibration:
    rng = np.random.default_rng(seed)

    def rotation(scale):
        return k.axis_rotation(_unit(rng.normal(size=3)), rng.normal(0, scale))

    offsets = {}
    for s in ("r", "l"):
        offsets[f"hip_{s}"] = np.eye(3)
        offsets[f"knee_{s}"] = rotation(0.2)
        offsets[f"ankle_{s}"] = rotation(0.3)
    return k.Calibration(
        frames={},
        origins={},
        templates={},
        offsets=offsets,
        hip_m={"right": np.array([0.0, -0.09, 0.0]), "left": np.array([0.0, 0.09, 0.0])},
        knee_m={"right": np.array([0.01, 0.0, -0.40]), "left": np.array([-0.01, 0.0, -0.41])},
        ankle_m={"right": np.array([0.0, 0.01, -0.39]), "left": np.array([0.0, -0.01, -0.38])},
    )


def _unit(v):
    return v / np.linalg.norm(v)


def _coordinates(rng, count):
    q = np.zeros((count, 17))
    q[:, :3] = rng.normal([0.3, 0.0, 0.9], 0.05, (count, 3))
    axis = np.array([_unit(a) for a in rng.normal(size=(count, 3))])
    angle = rng.uniform(0, 0.3, count)
    q[:, 3:6] = axis * np.sin(angle / 2)[:, None]
    q[:, 6] = np.cos(angle / 2)
    for i in range(2):
        q[:, 7 + 5 * i : 12 + 5 * i] = rng.uniform([-0.5, -0.2, -0.3, 0.1, -0.4], [0.8, 0.2, 0.3, 1.8, 0.4], (count, 5))
    return q


class TestKinematics3D(unittest.TestCase):
    def test_hip_decomposition_inverts_composition(self):
        """Intrinsic flexion-adduction-rotation angles round-trip for both legs."""
        rng = np.random.default_rng(1)
        angles = rng.uniform([-0.8, -0.4, -0.6], [1.2, 0.4, 0.6], (50, 3))
        for side in ("right", "left"):
            np.testing.assert_allclose(k.hip_angles(k.hip_matrix(angles, side), side), angles, atol=1e-12)

    def test_coordinates_recover_consistent_motion(self):
        """Segment frames generated by the model decompose back to the same coordinates."""
        calibration = _calibration()
        rng = np.random.default_rng(2)
        q = _coordinates(rng, 30)
        frames = k.model_frames(q, calibration)
        tracked = {
            "rotations": {
                name: frames[name]
                for name in ("pelvis", "thigh_r", "shank_r", "foot_r", "thigh_l", "shank_l", "foot_l")
            },
            "centers": {
                name: frames[name] for name in ("hip_mid", "hip_r", "knee_r", "ankle_r", "hip_l", "knee_l", "ankle_l")
            },
        }
        recovered = k.coordinates(tracked, calibration)
        np.testing.assert_allclose(recovered[:, :3], q[:, :3], atol=1e-12)
        np.testing.assert_allclose(np.abs(np.sum(recovered[:, 3:7] * q[:, 3:7], axis=1)), 1.0, atol=1e-12)
        np.testing.assert_allclose(recovered[:, 7:], q[:, 7:], atol=1e-9)
        refined, report = k.fit_legs(recovered, tracked, calibration)
        np.testing.assert_allclose(refined[:, 7:], q[:, 7:], atol=1e-6)
        self.assertLess(report["right"]["ankle_error_peak_m"], 1e-6)

    def test_newton_articulation_matches_numpy_kinematics(self):
        """The Newton model's forward kinematics reproduces the NumPy body frames and ankles."""
        import newton  # noqa: PLC0415
        from projects.impedance_instron.bilateral import model3d  # noqa: PLC0415

        calibration = _calibration(3)
        q = _coordinates(np.random.default_rng(4), 6)
        profile = {
            "masses_kg": [8.0, 3.3, 1.4],
            "com_local_m": [[0.17, 0.0], [0.17, 0.0], [0.025, -0.047]],
            "inertias_kg_m2": [0.13, 0.035, 0.006],
        }
        model = model3d.build_worlds([calibration], np.zeros(len(q), dtype=int), profile, 66.5, None, "cpu")
        state = model.state()
        state.joint_q.assign(q.ravel().astype(np.float32))
        newton.eval_fk(model, state.joint_q, state.joint_qd, state)
        body_q = state.body_q.numpy().reshape(len(q), 7, 7)
        frames = k.model_frames(q, calibration)
        for b, name in enumerate(model3d.BODIES):
            x, y, z, w = body_q[:, b, 3:].T
            rotation = np.stack(
                (
                    np.stack((1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)), -1),
                    np.stack((2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)), -1),
                    np.stack((2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)), -1),
                ),
                axis=-2,
            )
            self.assertLess(float(np.max(k.angle_between(rotation, frames[name]))), 2e-3)
        for s, b in (("r", 3), ("l", 6)):
            np.testing.assert_allclose(body_q[:, b, :3], frames[f"ankle_{s}"], atol=2e-6)
        self.assertAlmostEqual(float(model.body_mass.numpy()[:7].sum()), 66.5, places=4)

    def test_3d_seed_action_is_finite(self):
        """The 3D engineering seed maps to finite logits inside every impedance bound."""
        from projects.impedance_instron.bilateral import env3d  # noqa: PLC0415

        self.assertTrue(math.isfinite(float(env3d.seed_action().sum())))


class TestActuation(unittest.TestCase):
    """The 3D actuation follows the planar decision: no torque lag and no slew bound."""

    SPRING_STIFFNESS_NM_RAD = 400.0
    EQUILIBRIUM_RAD = 0.5

    def _one_substep(self, params):
        """Actuate one substep of a world held at zero position error and command the joint torque."""
        import warp as wp  # noqa: PLC0415

        from projects.impedance_instron.bilateral import env3d, model3d  # noqa: PLC0415

        joints = model3d.ACTUATED
        data = env3d.Worlds3D()
        for name, dtype in (
            ("status", int),
            ("torque", env3d.VecJ),
            ("load", env3d.VecJ),
            ("equilibrium", env3d.VecJ),
            ("stiffness", env3d.VecJ),
            ("damping", env3d.VecJ),
        ):
            setattr(data, name, wp.zeros(1, dtype=dtype, device="cpu"))
        # The hip flexion spring alone commands stiffness * equilibrium, well above what
        # Bounds3D.torque_rate_max_nm_s allows in one 1.25e-4 s substep.
        equilibrium = np.zeros(joints)
        equilibrium[0] = self.EQUILIBRIUM_RAD
        stiffness = np.zeros(joints)
        stiffness[0] = self.SPRING_STIFFNESS_NM_RAD
        data.equilibrium.assign(equilibrium[None].astype(np.float32))
        data.stiffness.assign(stiffness[None].astype(np.float32))
        joint_q = wp.zeros(7 + joints, dtype=float, device="cpu")
        joint_qd = wp.zeros(6 + joints, dtype=float, device="cpu")
        joint_f = wp.zeros(6 + joints, dtype=float, device="cpu")
        wp.launch(env3d._actuate, dim=1, inputs=[params, data, joint_q, joint_qd, joint_f], device="cpu")
        return float(data.torque.numpy()[0][0]), float(joint_f.numpy()[6])

    def test_default_config_delivers_the_commanded_torque_in_one_substep(self):
        """Zero response time and no slew limit apply the impedance command without a ramp."""
        from dataclasses import replace  # noqa: PLC0415

        from projects.impedance_instron.bilateral import env3d  # noqa: PLC0415

        config = env3d.Env3DConfig()
        bounds = env3d.Bounds3D()
        command = self.SPRING_STIFFNESS_NM_RAD * self.EQUILIBRIUM_RAD
        torque, load = self._one_substep(env3d._params(config, bounds, 700.0))
        self.assertAlmostEqual(torque, command, delta=1e-3)
        self.assertAlmostEqual(load, command, delta=1e-3)

        limited = env3d._params(replace(config, torque_slew_limit=True), bounds, 700.0)
        ramped, _ = self._one_substep(limited)
        self.assertLess(ramped, bounds.torque_rate_max_nm_s[0] * config.dt_s + 1e-3)


class TestMountShift(unittest.TestCase):
    """Per-side mounts shift each world's shoe carrier within the foot frame."""

    def test_shift_places_the_ankle_at_each_side_static_height(self):
        """A taller static ankle moves the shoe down in the foot frame."""
        from types import SimpleNamespace  # noqa: PLC0415

        from projects.impedance_instron.bilateral import env3d  # noqa: PLC0415

        heights = {"A": {"right": 0.090, "left": 0.094}, "B": {"right": 0.086, "left": 0.090}}
        shoe = {"mount_m": [-0.03, 0.0, 0.090], "static_calibration": {"ankle_height_m": heights}}
        library = SimpleNamespace(manifest={"shoe": shoe}, trials=["A", "B"])
        shifts = env3d._mount_shifts(library, np.array([0, 1, 1]))
        np.testing.assert_allclose(shifts[:, :, 2], [[0.0, -0.004], [0.004, 0.0], [0.004, 0.0]], atol=1e-7)
        np.testing.assert_array_equal(shifts[:, :, :2], 0.0)

    def test_shifted_carrier_moves_with_the_foot_and_transfers_its_wrench(self):
        """The carrier twist is the foot's velocity at the shifted origin, and its wrench reaches the COM."""
        import warp as wp  # noqa: PLC0415

        from projects.impedance_instron.bilateral import env3d  # noqa: PLC0415

        @wp.kernel
        def probe(
            body_q: wp.array[wp.transform],
            body_qd: wp.array[wp.spatial_vector],
            body_com: wp.array[wp.vec3],
            shift: wp.vec3,
            wrench: wp.spatial_vector,
            carrier_q: wp.array[wp.transform],
            carrier_qd: wp.array[wp.spatial_vector],
            body_f: wp.array[wp.spatial_vector],
        ):
            pose, twist = env3d._carrier(body_q, body_qd, body_com, 0, shift)
            carrier_q[0] = pose
            carrier_qd[0] = twist
            env3d._apply(body_q, body_com, body_f, 0, shift, wrench)

        rotation = wp.quat_from_axis_angle(wp.normalize(wp.vec3(0.3, -0.5, 0.8)), 0.7)
        pose = wp.transform(wp.vec3(0.4, -0.1, 0.2), rotation)
        com, shift = np.array([0.02, 0.01, -0.03]), np.array([0.0, 0.0, -0.004])
        velocity, omega = np.array([3.0, 0.2, -1.0]), np.array([0.5, -4.0, 1.5])
        force, torque = np.array([30.0, -20.0, 900.0]), np.array([1.0, 2.0, -0.5])
        arrays = [
            wp.array([pose], dtype=wp.transform, device="cpu"),
            wp.array([wp.spatial_vector(*velocity, *omega)], dtype=wp.spatial_vector, device="cpu"),
            wp.array([wp.vec3(*com)], dtype=wp.vec3, device="cpu"),
        ]
        carrier_q = wp.zeros(1, dtype=wp.transform, device="cpu")
        carrier_qd = wp.zeros(1, dtype=wp.spatial_vector, device="cpu")
        body_f = wp.zeros(1, dtype=wp.spatial_vector, device="cpu")
        wp.launch(
            probe,
            dim=1,
            inputs=[*arrays, wp.vec3(*shift), wp.spatial_vector(*force, *torque), carrier_q, carrier_qd, body_f],
            device="cpu",
        )
        R = np.array(wp.quat_to_matrix(rotation)).reshape(3, 3)
        origin = np.array(pose.p) + R @ shift
        np.testing.assert_allclose(carrier_q.numpy()[0][:3], origin, atol=1e-6)
        # body_qd carries the COM velocity; the carrier origin sits at R (shift - com) from the COM.
        arm = R @ (shift - com)
        np.testing.assert_allclose(carrier_qd.numpy()[0][:3], velocity + np.cross(omega, arm), atol=1e-5)
        np.testing.assert_allclose(body_f.numpy()[0][3:], torque + np.cross(arm, force), atol=1e-4)


